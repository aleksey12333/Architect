namespace AIArchitectStudio.Services;

/// <summary>Вкладка справочного центра.</summary>
public enum HelpTab
{
    QuickStart,
    Methods,
    Keys,
    Imports
}

/// <summary>Карточка справки: вкладка, заголовок, глиф, текст, пункт норм или место в интерфейсе, ключевые слова поиска.</summary>
public sealed record HelpTopic(HelpTab Tab, string Title, string Glyph, string Body, string Reference = "", string Keywords = "")
{
    /// <summary>Совпадение с поисковой строкой (все слова запроса — в заголовке, тексте, ссылке или ключевых словах; без учёта регистра).</summary>
    public bool Matches(string? query)
    {
        if (string.IsNullOrWhiteSpace(query)) return true;
        string hay = $"{Title} {Body} {Reference} {Keywords}";
        return query.Split(' ', StringSplitOptions.RemoveEmptyEntries).All(w => hay.Contains(w, StringComparison.OrdinalIgnoreCase));
    }
}

/// <summary>Горячая клавиша или жест мыши: сочетание, действие, где работает.</summary>
public sealed record HelpHotKey(string Keys, string Action, string Context)
{
    public bool Matches(string? query) =>
        string.IsNullOrWhiteSpace(query) || query.Split(' ', StringSplitOptions.RemoveEmptyEntries).All(w => $"{Keys} {Action} {Context}".Contains(w, StringComparison.OrdinalIgnoreCase));
}

