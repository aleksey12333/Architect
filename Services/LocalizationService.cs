    [ObservableProperty]
    public partial string Language { get; set; } = Russian;

    public bool IsRussian => Language == Russian;

    public CultureInfo Culture => IsRussian ? CultureInfo.GetCultureInfo("ru-RU") : CultureInfo.GetCultureInfo("en-US");

    partial void OnLanguageChanged(string value)
    {
        OnPropertyChanged(nameof(IsRussian));
        OnPropertyChanged(nameof(Culture));
        // Индексатор: обновить все привязки вида L["Key"].
        OnPropertyChanged("Item[]");
    }

    /// <summary>Индексатор для кода и классических Binding.</summary>
    public string this[string key] => Get(key);

    /// <summary>Функция для x:Bind: второй аргумент нужен только для реактивной переоценки привязки.</summary>
    public string T(string key, string language) => Get(key, language);

    public string Get(string key) => Get(key, Language);

    public string Format(string key, params object[] args) => string.Format(Culture, Get(key), args);

    public void Toggle() => Language = IsRussian ? English : Russian;

    /// <summary>Строка словаря для заданного языка без экземпляра сервиса (подписи моделей данных, например сообщений чата).</summary>
    public static string Lookup(string key, string language) => Get(key, language);

    private static string Get(string key, string language)
    {
        if (!Strings.TryGetValue(key, out var pair) && !LibraryStrings.TryGetValue(key, out pair) && !Wave1Strings.TryGetValue(key, out pair) &&
            !Wave2Strings.TryGetValue(key, out pair) && !Wave3Strings.TryGetValue(key, out pair) && !Wave4Strings.TryGetValue(key, out pair) &&
            !Wave41Strings.TryGetValue(key, out pair) && !Wave5Strings.TryGetValue(key, out pair)) return key;
        return language == English ? pair.En : pair.Ru;
    }
